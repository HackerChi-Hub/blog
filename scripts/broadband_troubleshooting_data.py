def get_isp_by_name(name: str):
    """按运营商名称查询联系方式"""
    for isp in ISP_CONTACTS:
        if name in isp["name"]:
            return isp
    return None


def get_error_code(code: str):
    """按错误代码查询详情"""
    for err in ERROR_CODES:
        if err["code"] == code:
            return err
    return None


def get_indicator_status(indicator_name: str, color: str):
    """查询指定指示灯在指定颜色下的含义"""
    for ind in MODEM_INDICATORS:
        if indicator_name.upper() in ind["name"].upper():
            for state in ind["states"]:
                if color in state["color"]:
                    return state
    return None


